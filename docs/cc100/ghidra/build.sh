#!/bin/sh
# Regenerate ../decompiled.c from ../../cc100ver230.bin with ../symbols.txt applied.
# Needs Ghidra 12.x and the H8S module from ./H8S installed as an extension, e.g.
#   ln -s "$PWD/H8S" ~/Library/ghidra/ghidra_<version>_PUBLIC/Extensions/H8S   (macOS)
#   ln -s "$PWD/H8S" ~/.config/ghidra/ghidra_<version>_PUBLIC/Extensions/H8S    (Linux)
set -e
GHIDRA=${GHIDRA:-/opt/homebrew/opt/ghidra/libexec}
D=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
"$GHIDRA/support/sleigh" "$D/H8S/data/languages/h8s_advanced.slaspec" > /dev/null 2>&1
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
"$GHIDRA/support/analyzeHeadless" "$T" CC100 \
	-import "$D/../../cc100ver230.bin" -loader BinaryLoader -processor H8S:BE:32:advanced \
	-scriptPath "$D/scripts" -preScript Setup.java \
	-postScript Names.java "$D/../symbols.txt" \
	-postScript Funcs.java "$D/../functions.txt" \
	-postScript Dump.java "$T/out.c" > "$T/log" 2>&1 || { cat "$T/log"; exit 1; }
grep -E "Names.java>|Dump.java>" "$T/log" || true
{
	echo "/* CC100 firmware 2.30 (cc100ver230.bin) -- raw Ghidra decompilation, H8S advanced mode."
	echo " * Generated by ghidra/build.sh with symbols.txt applied. Hand-cleaned code is in src/. */"
	echo
	cat "$T/out.c"
} > "$D/../decompiled.c"
